package talpadbFunctions

import (
	"fmt"
	"strings"

	talpadbDtos "docker-manager-go/src/talpadb/dtos"
)

type RelationDdlInfo struct {
	QualifiedName  string
	QuotedSchema   string
	Kind           string
	Persistence    string
	QuotedOwner    string
	Comment        *string
	ViewDefinition *string
	PartitionKey   *string
	Options        []string
	Tablespace     *string
	ForeignServer  *string
}

type SequenceDdlInfo struct {
	QualifiedName string
	QuotedOwner   string
	DataType      string
	Start         int64
	Increment     int64
	MinValue      int64
	MaxValue      int64
	Cache         int64
	Cycle         bool
}

type FunctionDdlInfo struct {
	Signature   string
	IsProcedure bool
	QuotedOwner string
	Definition  string
}

func QuoteLiteral(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "''") + "'"
}

func withSemicolon(statement string) string {
	trimmed := strings.TrimRight(strings.TrimSpace(statement), ";")
	return strings.TrimRight(trimmed, " \n\t") + ";"
}

func columnDefinition(column talpadbDtos.ColumnDto) string {
	definition := "    " + column.QuotedName + " " + column.DataType
	if column.Collation != nil {
		definition += " COLLATE " + *column.Collation
	}

	switch {
	case column.Identity == "a":
		definition += " GENERATED ALWAYS AS IDENTITY"
	case column.Identity == "d":
		definition += " GENERATED BY DEFAULT AS IDENTITY"
	case column.Generated == "s" && column.DefaultValue != nil:
		definition += " GENERATED ALWAYS AS (" + *column.DefaultValue + ") STORED"
	case column.Generated == "v" && column.DefaultValue != nil:
		definition += " GENERATED ALWAYS AS (" + *column.DefaultValue + ") VIRTUAL"
	case column.DefaultValue != nil:
		definition += " DEFAULT " + *column.DefaultValue
	}

	if column.NotNull {
		definition += " NOT NULL"
	}
	return definition
}

func writeComments(builder *strings.Builder, objectType string, relation RelationDdlInfo, columns []talpadbDtos.ColumnDto) {
	if relation.Comment != nil {
		fmt.Fprintf(builder, "\nCOMMENT ON %s %s\n    IS %s;\n", objectType, relation.QualifiedName, QuoteLiteral(*relation.Comment))
	}
	for _, column := range columns {
		if column.Comment != nil {
			fmt.Fprintf(builder, "\nCOMMENT ON COLUMN %s.%s\n    IS %s;\n", relation.QualifiedName, column.QuotedName, QuoteLiteral(*column.Comment))
		}
	}
}

func writeIndexes(builder *strings.Builder, relation RelationDdlInfo, indexes []talpadbDtos.IndexDto) {
	for _, index := range indexes {
		if index.ConstraintBacked {
			continue
		}
		fmt.Fprintf(builder, "\n-- Index: %s\n\n-- DROP INDEX IF EXISTS %s.%s;\n\n%s;\n", index.Name, relation.QuotedSchema, index.QuotedName, index.Definition)
	}
}

func writeTriggers(builder *strings.Builder, triggers []talpadbDtos.TriggerDto) {
	for _, trigger := range triggers {
		fmt.Fprintf(builder, "\n-- Trigger: %s\n\n%s;\n", trigger.Name, trigger.Definition)
		if !trigger.Enabled {
			builder.WriteString("-- (trigger desabilitado)\n")
		}
	}
}

func BuildTableDdl(relation RelationDdlInfo, columns []talpadbDtos.ColumnDto, constraints []talpadbDtos.ConstraintDto, indexes []talpadbDtos.IndexDto, triggers []talpadbDtos.TriggerDto) string {
	var builder strings.Builder

	objectType := "TABLE"
	createStatement := "CREATE TABLE IF NOT EXISTS"
	switch {
	case relation.Kind == "f":
		objectType = "FOREIGN TABLE"
		createStatement = "CREATE FOREIGN TABLE IF NOT EXISTS"
	case relation.Persistence == "u":
		createStatement = "CREATE UNLOGGED TABLE IF NOT EXISTS"
	}

	fmt.Fprintf(&builder, "-- Table: %s\n\n-- DROP %s IF EXISTS %s;\n\n", relation.QualifiedName, objectType, relation.QualifiedName)

	lines := make([]string, 0, len(columns)+len(constraints))
	for _, column := range columns {
		lines = append(lines, columnDefinition(column))
	}
	for _, constraint := range constraints {
		if !constraint.IsLocal {
			continue
		}
		lines = append(lines, "    CONSTRAINT "+constraint.QuotedName+" "+constraint.Definition)
	}

	fmt.Fprintf(&builder, "%s %s\n(\n%s\n)", createStatement, relation.QualifiedName, strings.Join(lines, ",\n"))
	if relation.PartitionKey != nil && *relation.PartitionKey != "" {
		builder.WriteString("\nPARTITION BY " + *relation.PartitionKey)
	}
	if relation.ForeignServer != nil {
		builder.WriteString("\nSERVER " + *relation.ForeignServer)
	}
	if len(relation.Options) > 0 {
		builder.WriteString("\nWITH (\n    " + strings.Join(relation.Options, ",\n    ") + "\n)")
	}
	if relation.Tablespace != nil {
		builder.WriteString("\nTABLESPACE " + *relation.Tablespace)
	}
	builder.WriteString(";\n")

	fmt.Fprintf(&builder, "\nALTER %s IF EXISTS %s\n    OWNER TO %s;\n", objectType, relation.QualifiedName, relation.QuotedOwner)
	writeComments(&builder, objectType, relation, columns)
	writeIndexes(&builder, relation, indexes)
	writeTriggers(&builder, triggers)

	return builder.String()
}

func BuildViewDdl(relation RelationDdlInfo, columns []talpadbDtos.ColumnDto, indexes []talpadbDtos.IndexDto, triggers []talpadbDtos.TriggerDto) string {
	var builder strings.Builder

	definition := ""
	if relation.ViewDefinition != nil {
		definition = strings.TrimRight(strings.TrimSpace(*relation.ViewDefinition), ";")
	}

	if relation.Kind == "m" {
		fmt.Fprintf(&builder, "-- Materialized View: %s\n\n-- DROP MATERIALIZED VIEW IF EXISTS %s;\n\n", relation.QualifiedName, relation.QualifiedName)
		fmt.Fprintf(&builder, "CREATE MATERIALIZED VIEW IF NOT EXISTS %s\nAS\n %s\nWITH DATA;\n", relation.QualifiedName, definition)
		fmt.Fprintf(&builder, "\nALTER MATERIALIZED VIEW IF EXISTS %s\n    OWNER TO %s;\n", relation.QualifiedName, relation.QuotedOwner)
		writeComments(&builder, "MATERIALIZED VIEW", relation, columns)
		writeIndexes(&builder, relation, indexes)
		return builder.String()
	}

	fmt.Fprintf(&builder, "-- View: %s\n\n-- DROP VIEW IF EXISTS %s;\n\n", relation.QualifiedName, relation.QualifiedName)
	fmt.Fprintf(&builder, "CREATE OR REPLACE VIEW %s\n AS\n %s;\n", relation.QualifiedName, definition)
	fmt.Fprintf(&builder, "\nALTER VIEW %s\n    OWNER TO %s;\n", relation.QualifiedName, relation.QuotedOwner)
	writeComments(&builder, "VIEW", relation, columns)
	writeTriggers(&builder, triggers)
	return builder.String()
}

func BuildSequenceDdl(sequence SequenceDdlInfo) string {
	var builder strings.Builder
	fmt.Fprintf(&builder, "-- SEQUENCE: %s\n\n-- DROP SEQUENCE IF EXISTS %s;\n\n", sequence.QualifiedName, sequence.QualifiedName)
	fmt.Fprintf(&builder, "CREATE SEQUENCE IF NOT EXISTS %s\n", sequence.QualifiedName)
	fmt.Fprintf(&builder, "    AS %s\n    INCREMENT %d\n    START %d\n    MINVALUE %d\n    MAXVALUE %d\n    CACHE %d", sequence.DataType, sequence.Increment, sequence.Start, sequence.MinValue, sequence.MaxValue, sequence.Cache)
	if sequence.Cycle {
		builder.WriteString("\n    CYCLE")
	}
	builder.WriteString(";\n")
	fmt.Fprintf(&builder, "\nALTER SEQUENCE %s\n    OWNER TO %s;\n", sequence.QualifiedName, sequence.QuotedOwner)
	return builder.String()
}

func BuildFunctionDdl(function FunctionDdlInfo) string {
	objectType := "FUNCTION"
	if function.IsProcedure {
		objectType = "PROCEDURE"
	}

	var builder strings.Builder
	fmt.Fprintf(&builder, "-- %s: %s\n\n-- DROP %s IF EXISTS %s;\n\n", objectType, function.Signature, objectType, function.Signature)
	builder.WriteString(withSemicolon(function.Definition) + "\n")
	fmt.Fprintf(&builder, "\nALTER %s %s\n    OWNER TO %s;\n", objectType, function.Signature, function.QuotedOwner)
	return builder.String()
}

func BuildSchemaDdl(quotedName string, quotedOwner string, comment *string) string {
	var builder strings.Builder
	fmt.Fprintf(&builder, "-- SCHEMA: %s\n\n-- DROP SCHEMA IF EXISTS %s ;\n\n", quotedName, quotedName)
	fmt.Fprintf(&builder, "CREATE SCHEMA IF NOT EXISTS %s\n    AUTHORIZATION %s;\n", quotedName, quotedOwner)
	if comment != nil {
		fmt.Fprintf(&builder, "\nCOMMENT ON SCHEMA %s\n    IS %s;\n", quotedName, QuoteLiteral(*comment))
	}
	return builder.String()
}
